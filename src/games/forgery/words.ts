/** Lowercase, trimmed, single-spaced: the form a guess is compared in. */
export function normalizeGuess(text: string): string {
  return text.toLowerCase().replace(/[^a-z ]/g, '').replace(/\s+/g, ' ').trim();
}

/** Words to offer for what has been typed so far: words that start with it first, then words that contain it. */
export function suggestWords(typed: string, limit = 6): string[] {
  const q = normalizeGuess(typed);
  if (!q) return [];
  const starts: string[] = [];
  const inside: string[] = [];
  for (const w of GUESS_WORDS) {
    if (w.startsWith(q)) starts.push(w);
    else if (w.includes(q)) inside.push(w);
  }
  return [...starts, ...inside].slice(0, limit);
}
